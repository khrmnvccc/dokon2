-- Checkout: buyurtmaga bonus qoʻllash (server, buyurtma yaratilgandan keyin darhol). Qancha qoʻllangani qaytadi.
create or replace function public._bonus_apply(p_order uuid, p_amount bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  o public.orders;
  cfg jsonb := coalesce((select value from public.site_settings where key = 'bonus'), '{}'::jsonb);
  v_bal bigint;
  v_max bigint;
  v_use bigint;
begin
  if coalesce((cfg ->> 'enabled')::boolean, false) is not true or coalesce((cfg ->> 'spend_enabled')::boolean, true) is not true then return 0; end if;
  select * into o from public.orders where id = p_order for update;
  if not found or o.user_id is null or o.bonus_used > 0 or o.status <> 'new' or o.payment_status = 'paid' then return 0; end if;
  perform pg_advisory_xact_lock(hashtext('bonus:' || o.user_id::text));
  v_bal := public.bonus_balance(o.user_id);
  if v_bal < greatest(coalesce((cfg ->> 'min_balance')::bigint, 0), 1) then return 0; end if;
  v_max := floor(greatest(o.total - o.shipping_cost, 0) * least(greatest(coalesce((cfg ->> 'max_spend_percent')::numeric, 50), 0), 100) / 100);
  v_use := least(greatest(coalesce(p_amount, 0), 0), v_bal, v_max);
  if v_use <= 0 then return 0; end if;
  update public.orders set bonus_used = v_use, discount_total = discount_total + v_use, total = total - v_use, updated_at = now() where id = o.id;
  insert into public.bonus_ledger (user_id, amount, kind, order_id, note) values (o.user_id, -v_use, 'spend', o.id, 'Buyurtma №' || o.number);
  return v_use;
end;
$$;
revoke all on function public._bonus_apply(uuid, bigint) from public, anon, authenticated;
grant execute on function public._bonus_apply(uuid, bigint) to service_role;

-- Holat oʻzgarganda: yetkazildi — keshbek; bekor/qaytarildi — ishlatilgan bonus qaytadi, keshbek qaytarib olinadi.
create or replace function public._bonus_on_status()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  cfg jsonb := coalesce((select value from public.site_settings where key = 'bonus'), '{}'::jsonb);
  v_pct numeric;
  v_base bigint;
  v_earn bigint;
  v_spent bigint;
  v_got bigint;
begin
  if new.user_id is null or new.status is not distinct from old.status then return null; end if;
  if new.status = 'delivered' and coalesce((cfg ->> 'enabled')::boolean, false) then
    v_pct := least(greatest(coalesce((cfg ->> 'earn_percent')::numeric, 0), 0), 100);
    v_base := greatest(new.total - new.shipping_cost - coalesce(new.delivery_fee, 0), 0);
    if v_pct > 0 and v_base >= coalesce((cfg ->> 'min_order')::bigint, 0) then
      v_earn := floor(v_base * v_pct / 100);
      if v_earn > 0 then
        insert into public.bonus_ledger (user_id, amount, kind, order_id, note)
        values (new.user_id, v_earn, 'earn', new.id, 'Keshbek · №' || new.number)
        on conflict do nothing;
        if found then
          insert into public.notifications (user_id, type, title, body, link)
          values (new.user_id, 'bonus', 'Sizga ' || v_earn || ' soʻm bonus tushdi', 'Buyurtma №' || new.number || ' uchun keshbek', '/account/bonus');
        end if;
      end if;
    end if;
  elsif new.status in ('cancelled', 'returned') then
    select -sum(amount) into v_spent from public.bonus_ledger where order_id = new.id and kind = 'spend';
    if coalesce(v_spent, 0) > 0 then
      insert into public.bonus_ledger (user_id, amount, kind, order_id, note)
      values (new.user_id, v_spent, 'refund', new.id, 'Bekor qilindi · №' || new.number) on conflict do nothing;
    end if;
    select sum(amount) into v_got from public.bonus_ledger where order_id = new.id and kind = 'earn';
    if coalesce(v_got, 0) > 0 then
      insert into public.bonus_ledger (user_id, amount, kind, order_id, note)
      values (new.user_id, -v_got, 'reverse', new.id, 'Qaytarildi · №' || new.number) on conflict do nothing;
    end if;
  end if;
  return null;
end;
$$;
revoke all on function public._bonus_on_status() from public, anon, authenticated;
create or replace trigger bonus_on_status after update of status on public.orders
  for each row execute function public._bonus_on_status();

-- Xodim: qoʻlda qoʻshish / ayirish
create or replace function public.admin_bonus_adjust(p_user uuid, p_amount bigint, p_note text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.has_perm('coupons.write') then raise exception 'FORBIDDEN' using errcode = '42501'; end if;
  if p_amount is null or p_amount = 0 or abs(p_amount) > 1000000000 then raise exception 'BAD_AMOUNT' using errcode = 'P0001'; end if;
  if not exists (select 1 from public.profiles where id = p_user) then raise exception 'NOT_FOUND' using errcode = 'P0001'; end if;
  perform pg_advisory_xact_lock(hashtext('bonus:' || p_user::text));
  if p_amount < 0 and public.bonus_balance(p_user) + p_amount < 0 then raise exception 'BALANCE' using errcode = 'P0001'; end if;
  insert into public.bonus_ledger (user_id, amount, kind, note, created_by)
  values (p_user, p_amount, 'adjust', left(nullif(trim(coalesce(p_note, '')), ''), 300), auth.uid());
  return public.bonus_balance(p_user);
end;
$$;
revoke all on function public.admin_bonus_adjust(uuid, bigint, text) from public, anon;
grant execute on function public.admin_bonus_adjust(uuid, bigint, text) to authenticated, service_role;

