-- Mijoz narxni qabul qildi: buyurtma yaratiladi (mahsulot katalogda yoʻq — qator nomi bilan).
create or replace function public._import_request_to_order(p_id uuid, p_user uuid, p_payment_method uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  r public.import_requests;
  pm public.payment_methods;
  v_order public.orders;
  q jsonb;
  v_item bigint; v_service bigint; v_cargo bigint; v_total bigint;
  v_name text;
begin
  select * into r from public.import_requests where id = p_id for update;
  if not found or r.user_id is distinct from p_user then raise exception 'NOT_FOUND' using errcode = 'P0001'; end if;
  if r.status = 'accepted' and r.order_id is not null then
    select * into v_order from public.orders where id = r.order_id;
    return jsonb_build_object('id', v_order.id, 'number', v_order.number, 'token', v_order.public_token, 'duplicate', true);
  end if;
  if r.status <> 'quoted' or r.quote is null then raise exception 'NOT_QUOTED' using errcode = 'P0001'; end if;
  q := r.quote;
  if nullif(q ->> 'valid_until', '') is not null and (q ->> 'valid_until')::timestamptz < now() then
    raise exception 'QUOTE_EXPIRED' using errcode = 'P0001';
  end if;
  select * into pm from public.payment_methods where id = p_payment_method and is_active;
  if not found then raise exception 'PAYMENT_METHOD' using errcode = 'P0001'; end if;
  if exists (select 1 from public.profiles where id = p_user and is_blocked) then raise exception 'USER_BLOCKED' using errcode = 'P0001'; end if;

  v_item := greatest(coalesce((q ->> 'item_price')::bigint, 0), 0);
  v_service := greatest(coalesce((q ->> 'service_fee')::bigint, 0), 0);
  v_cargo := greatest(coalesce((q ->> 'cargo_fee')::bigint, 0), 0);
  v_total := v_item * r.quantity + v_service + v_cargo;
  if v_total <= 0 then raise exception 'NOT_QUOTED' using errcode = 'P0001'; end if;
  v_name := coalesce(nullif(trim(coalesce(q ->> 'name', '')), ''), nullif(trim(coalesce(r.title, '')), ''), 'Buyurtma asosida №' || r.number);

  insert into public.orders (
    user_id, payment_method_id, payment_method_name, payment_provider, shipping_method_id, shipping_method_name,
    customer_name, customer_phone, comment, subtotal, discount_total, shipping_cost, total, items_count, idempotency_key
  ) values (
    p_user, pm.id, pm.name, pm.provider, null, 'Keyin tanlanadi',
    r.customer_name, r.customer_phone, left('Buyurtma asosida №' || r.number || coalesce(' · ' || nullif(q ->> 'note', ''), ''), 1000),
    v_total, 0, 0, v_total, r.quantity, 'import:' || r.id
  ) returning * into v_order;

  insert into public.order_items (order_id, product_id, variant_id, product_name, variant_name, sku, image_url, unit_price, original_price, quantity, discount, line_total)
  values (v_order.id, null, null, left(v_name, 300), null, 'REQ-' || r.number, null, v_item, v_item, r.quantity, 0, v_item * r.quantity);
  if v_service > 0 then
    insert into public.order_items (order_id, product_name, unit_price, original_price, quantity, line_total)
    values (v_order.id, 'Xizmat haqi', v_service, v_service, 1, v_service);
  end if;
  if v_cargo > 0 then
    insert into public.order_items (order_id, product_name, unit_price, original_price, quantity, line_total)
    values (v_order.id, 'Kargo (yetkazib kelish)', v_cargo, v_cargo, 1, v_cargo);
  end if;

  insert into public.order_status_history (order_id, status, note) values (v_order.id, 'new', 'Buyurtma asosida №' || r.number || ' qabul qilindi');
  insert into public.notifications (user_id, type, title, body, link)
  values (null, 'new_order', 'Yangi buyurtma #' || v_order.number, v_order.customer_name || ' — buyurtma asosida №' || r.number, '/admin/orders/' || v_order.id);
  update public.import_requests set status = 'accepted', order_id = v_order.id, updated_at = now() where id = r.id;
  return jsonb_build_object('id', v_order.id, 'number', v_order.number, 'token', v_order.public_token, 'duplicate', false);
end;
$$;
revoke all on function public._import_request_to_order(uuid, uuid, uuid) from public, anon, authenticated;
grant execute on function public._import_request_to_order(uuid, uuid, uuid) to service_role;

