-- Xodimning shaxsiy ruxsatlari va filiallari. perms NULL = rolining standart ruxsatlari;
-- branch_ids NULL = barcha filiallar.
create table if not exists public.staff_members (
  user_id uuid primary key references auth.users (id) on delete cascade,
  perms text[],
  branch_ids integer[],
