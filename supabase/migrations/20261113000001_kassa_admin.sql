-- ---------- Dashboard (kassa 1.10): jonli lenta, 14 kunlik grafik, kapsulalar, xodimlar reytingi ----------
-- p_branch NULL = barcha (ruxsat etilgan) filiallar. Filialga biriktirilgan xodim boshqa filialni ko'rmaydi.
create or replace function public.admin_dashboard_live(p_branch integer default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_today date := (now() at time zone 'Asia/Tashkent')::date;
  v_result jsonb;
begin
  if not public.has_perm('dashboard.view') then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;
  if p_branch is not null and not public.branch_ok(p_branch) then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;

  with o as (
    select * from public.orders
    where public.branch_ok(branch_id) and (p_branch is null or branch_id = p_branch)
  ), live as (
    select * from o where status not in ('cancelled', 'returned')
  )
  select jsonb_build_object(
    'today_sales', coalesce((select sum(total) from live where (created_at at time zone 'Asia/Tashkent')::date = v_today), 0),
    'yesterday_sales', coalesce((select sum(total) from live where (created_at at time zone 'Asia/Tashkent')::date = v_today - 1), 0),
    'today_orders', (select count(*) from o where (created_at at time zone 'Asia/Tashkent')::date = v_today),
    'yesterday_orders', (select count(*) from o where (created_at at time zone 'Asia/Tashkent')::date = v_today - 1),
    'new_orders', (select count(*) from o where status = 'new'),
    'undelivered', (select count(*) from o where status in ('confirmed', 'processing', 'shipped')),
    'low_stock', (select count(*) from public.products where is_active and track_stock and stock <= low_stock_threshold),
    'month_sales', coalesce((select sum(total) from live where created_at >= date_trunc('month', now() at time zone 'Asia/Tashkent') at time zone 'Asia/Tashkent'), 0),
    'sales_by_day', coalesce((
      select jsonb_agg(jsonb_build_object('date', d.day::date, 'revenue', coalesce(s.revenue, 0), 'orders', coalesce(s.orders, 0)) order by d.day)
      from generate_series(v_today - 13, v_today, interval '1 day') as d (day)
      left join (
        select (created_at at time zone 'Asia/Tashkent')::date as day, sum(total) as revenue, count(*) as orders
        from live where created_at >= (v_today - 14)::timestamp at time zone 'Asia/Tashkent'
        group by 1
      ) s on s.day = d.day::date
    ), '[]'::jsonb),
    'by_payment', coalesce((
      select jsonb_agg(jsonb_build_object('name', p.name, 'kind', p.kind, 'provider', p.provider, 'total', p.total) order by p.total desc) from (
        select coalesce(pm.name, l.payment_method_name) as name, coalesce(pm.kind, 'cash') as kind, pm.provider, sum(l.total) as total
        from live l left join public.payment_methods pm on pm.id = l.payment_method_id
        where l.created_at >= now() - interval '30 days'
        group by 1, 2, 3
      ) p
    ), '[]'::jsonb),
    'by_status', coalesce((
      select jsonb_agg(jsonb_build_object('status', s.status, 'count', s.n)) from (
        select status, count(*) as n from o where created_at >= now() - interval '30 days' group by status
      ) s
    ), '[]'::jsonb),
    'recent_orders', coalesce((
      select jsonb_agg(r) from (
        select id, number, customer_name, total, status, payment_method_name, created_at from o order by created_at desc limit 8
      ) r
    ), '[]'::jsonb),
    'staff_rating', coalesce((
      select jsonb_agg(r) from (
        select coalesce(pf.full_name, pf.email, 'Xodim') as name, count(*) as actions
        from public.order_status_history h
        join o on o.id = h.order_id
        left join public.profiles pf on pf.id = h.changed_by
        where h.changed_by is not null and h.created_at >= now() - interval '30 days'
        group by 1 order by count(*) desc limit 5
      ) r
    ), '[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;
grant execute on function public.admin_dashboard_live(integer) to authenticated;
