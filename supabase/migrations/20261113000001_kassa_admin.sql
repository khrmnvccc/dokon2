-- NULL = barcha filiallar (Ega yoki filial biriktirilmagan xodim).
create or replace function public.my_branches()
returns integer[]
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when exists (select 1 from public.user_roles where user_id = auth.uid() and role = 'super_admin') then null
    else (select sm.branch_ids from public.staff_members sm where sm.user_id = auth.uid())
  end;
$$;

create or replace function public.branch_ok(p_branch integer)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.my_branches() is null or p_branch = any (public.my_branches());
$$;

drop policy if exists dk_branches_select on public.branches;
create policy dk_branches_select on public.branches for select to authenticated
  using ((select public.is_staff()));
drop policy if exists dk_branches_write on public.branches;
create policy dk_branches_write on public.branches for all to authenticated
  using ((select public.is_owner())) with check ((select public.is_owner()));

-- Filialga biriktirilgan xodim faqat o'z filiali buyurtmalarini ko'radi va o'zgartiradi
-- (mijoz o'z buyurtmasini doim ko'radi).
drop policy if exists dk_orders_branch_select on public.orders;
create policy dk_orders_branch_select on public.orders as restrictive for select to authenticated
  using (user_id = (select auth.uid()) or (select public.branch_ok(branch_id)));
drop policy if exists dk_orders_branch_update on public.orders;
create policy dk_orders_branch_update on public.orders as restrictive for update to authenticated
  using ((select public.branch_ok(branch_id)));

drop policy if exists dk_staff_members_select on public.staff_members;
create policy dk_staff_members_select on public.staff_members for select to authenticated
  using (user_id = (select auth.uid()) or (select public.has_perm('staff.manage')));

-- Xodim ruxsatlari va filiallarini o'zgartirish. Qoidalar:
--  * Egani hech kim cheklay olmaydi; Admin'ni (manager) faqat Ega boshqaradi;
--  * hech kim o'zida yo'q ruxsatni boshqaga bera olmaydi; "messages.manage" ni faqat Ega beradi.
create or replace function public.admin_set_staff_access(p_user uuid, p_perms text[], p_branches integer[])
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_mine text[] := public.my_permissions();
  v_target_owner boolean;
  v_target_admin boolean;
begin
  if not public.has_perm('staff.manage') then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;
  select bool_or(role = 'super_admin'), bool_or(role = 'manager') into v_target_owner, v_target_admin
  from public.user_roles where user_id = p_user;
  if v_target_owner is null then
    raise exception 'USER_NOT_FOUND';
  end if;
  if v_target_owner then
    raise exception 'OWNER_LOCKED';
  end if;
  if v_target_admin and not public.is_owner() then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;
  if p_perms is not null then
    if not (p_perms <@ v_mine) then
      raise exception 'PERM_NOT_YOURS';
    end if;
    if 'messages.manage' = any (p_perms) and not public.is_owner() then
      raise exception 'FORBIDDEN' using errcode = '42501';
    end if;
  end if;
  if p_branches is not null and not public.is_owner()
     and public.my_branches() is not null and not (p_branches <@ public.my_branches()) then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;
  insert into public.staff_members (user_id, perms, branch_ids, updated_by, updated_at)
  values (p_user, p_perms, nullif(p_branches, '{}'), auth.uid(), now())
  on conflict (user_id) do update
    set perms = excluded.perms, branch_ids = excluded.branch_ids, updated_by = excluded.updated_by, updated_at = now();
end;
$$;

-- Xodimlar ro'yxati: shaxsiy ruxsatlar va filiallar bilan.
drop function if exists public.admin_staff();
create or replace function public.admin_staff()
returns table (user_id uuid, email text, full_name text, roles public.app_role[], perms text[], branch_ids integer[])
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.has_perm('staff.manage') then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;
  return query
  select ur.user_id, pf.email, pf.full_name, array_agg(ur.role order by ur.role), sm.perms, sm.branch_ids
  from public.user_roles ur
  left join public.profiles pf on pf.id = ur.user_id
  left join public.staff_members sm on sm.user_id = ur.user_id
  group by ur.user_id, pf.email, pf.full_name, sm.perms, sm.branch_ids
  order by pf.email;
end;
$$;

