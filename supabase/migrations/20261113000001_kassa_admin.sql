);
alter table public.staff_members enable row level security;

create or replace function public.is_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.user_roles where user_id = auth.uid() and role = 'super_admin');
$$;

-- Ega hech qachon cheklanmaydi; boshqalarda shaxsiy ro'yxat bo'lsa — o'sha, aks holda rol matritsasi.
create or replace function public.has_perm(p_permission text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when not exists (select 1 from public.user_roles where user_id = auth.uid()) then false
    when exists (select 1 from public.user_roles where user_id = auth.uid() and role = 'super_admin') then true
    when (select sm.perms from public.staff_members sm where sm.user_id = auth.uid()) is not null
      then exists (select 1 from public.staff_members sm where sm.user_id = auth.uid() and p_permission = any (sm.perms))
    else exists (
      select 1 from public.user_roles ur
      join public.role_permissions rp on rp.role = ur.role
      where ur.user_id = auth.uid() and rp.permission = p_permission
    )
  end;
$$;

create or replace function public.my_permissions()
returns text[]
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when not exists (select 1 from public.user_roles where user_id = auth.uid()) then '{}'::text[]
    when exists (select 1 from public.user_roles where user_id = auth.uid() and role = 'super_admin')
      then (select coalesce(array_agg(distinct permission order by permission), '{}') from public.role_permissions)
    when (select sm.perms from public.staff_members sm where sm.user_id = auth.uid()) is not null
      then (select sm.perms from public.staff_members sm where sm.user_id = auth.uid())
    else (
      select coalesce(array_agg(distinct rp.permission order by rp.permission), '{}')
      from public.user_roles ur join public.role_permissions rp on rp.role = ur.role
      where ur.user_id = auth.uid()
    )
  end;
$$;

