insert into public.app_meta (key, value) values ('schema_version', '"20261115000002"')
on conflict (key) do update set value = excluded.value, updated_at = now();

-- Har bir mijozning qisqa ID raqami. Mavjud mijozlarga ham avtomatik beriladi (roʻyxatdan oʻtish tartibida emas, jadval tartibida).
alter table public.profiles add column if not exists client_no bigint generated by default as identity (start with 1001);
create unique index if not exists profiles_client_no_idx on public.profiles (client_no);

-- ID hech qachon oʻzgarmaydi (mijoz ham, xodim ham oʻzgartira olmaydi).
create or replace function public.keep_client_no()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.client_no := old.client_no;
  return new;
end;
$$;
create or replace trigger keep_client_no before update on public.profiles
  for each row execute function public.keep_client_no();

-- Mijozlar roʻyxati: ID, Telegram belgisi; qidiruv ID (raqam yoki #1001), ism, telefon va email boʻyicha.
create or replace function public.admin_customers(p_q text default null, p_limit integer default 25, p_offset integer default 0)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_q text := nullif(trim(p_q), '');
  v_like text := case when v_q is null then null
    else '%' || replace(replace(replace(left(v_q, 100), '\', '\\'), '%', '\%'), '_', '\_') || '%' end;
  v_no bigint := case when v_q ~ '^#?[0-9]{1,12}$' then ltrim(v_q, '#')::bigint end;
  v_result jsonb;
begin
  if not public.has_perm('customers.read') then
    raise exception 'FORBIDDEN' using errcode = '42501';
  end if;

  with base as (
    select pf.*,
      (select count(*) from public.orders o where o.user_id = pf.id) as orders_count,
      (select coalesce(sum(o.total), 0) from public.orders o where o.user_id = pf.id and o.status not in ('cancelled', 'returned')) as total_spent,
      (select max(o.created_at) from public.orders o where o.user_id = pf.id) as last_order_at,
      (select ts.username from public.telegram_subscribers ts where ts.user_id = pf.id order by ts.created_at desc limit 1) as tg_username,
      exists (select 1 from public.telegram_subscribers ts where ts.user_id = pf.id) as via_telegram
    from public.profiles pf
    where v_q is null
      or pf.client_no = v_no
      or pf.full_name ilike v_like or pf.phone ilike v_like or pf.email ilike v_like
  )
  select jsonb_build_object(
    'total', (select count(*) from base),
    'items', coalesce((select jsonb_agg(b order by b.created_at desc) from (
      select id, client_no, full_name, phone, email, is_blocked, created_at, orders_count, total_spent, last_order_at, tg_username, via_telegram
      from base order by created_at desc limit least(p_limit, 100) offset greatest(p_offset, 0)
    ) b), '[]'::jsonb)
  ) into v_result;
  return v_result;
end;
$$;
grant execute on function public.admin_customers(text, integer, integer) to authenticated;
